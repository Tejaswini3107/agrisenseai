import cropStore from './cropStore';

// keep an in-memory current language so `t(null, ...)` can synchronously
// return localized strings. It is initialized from persistent storage
// and kept up-to-date via `cropStore.subscribeLanguage`.
let currentLanguage = FALLBACK_LANGUAGE;
(async () => {
  try {
    const lang = await cropStore.getLanguage();
    if (lang) currentLanguage = lang;
  } catch (e) {
    // ignore — fallback will be used
  }
})();

cropStore.subscribeLanguage((v) => {
  if (v) currentLanguage = v;
});

const getDictionary = (language) => TRANSLATIONS[(language || currentLanguage || FALLBACK_LANGUAGE).toLowerCase()] || TRANSLATIONS[FALLBACK_LANGUAGE];

export const t = (language, scope, key) => {
  const langToUse = language || currentLanguage || FALLBACK_LANGUAGE;
  const dictionary = getDictionary(langToUse);
  return dictionary?.[scope]?.[key] ?? TRANSLATIONS[FALLBACK_LANGUAGE]?.[scope]?.[key] ?? key;
};

