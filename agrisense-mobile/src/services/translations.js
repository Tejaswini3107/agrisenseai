const annotatePlaceholders = (obj, label) => {
  if (!obj || typeof obj !== 'object') return obj;
  Object.keys(obj).forEach((k) => {
    if (typeof obj[k] === 'string') {
      // avoid double-prefixing if already annotated
      if (!obj[k].startsWith('[')) obj[k] = `[${label}] ${obj[k]}`;
    } else if (typeof obj[k] === 'object') {
      annotatePlaceholders(obj[k], label);
    }
  });
};

